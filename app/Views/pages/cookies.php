            <h2>Qu'est-ce qu'un cookie ?</h2>
            <p>Un cookie est un petit fichier texte stocké sur votre appareil lorsque vous visitez un site web. Il
                permet au
                site de se souvenir de vos actions et préférences, comme la langue choisie, les informations de
                connexion ou
                d'autres paramètres.</p>

            <h2>Types de cookies que nous utilisons</h2>
            <p>Nous utilisons différents types de cookies sur notre site :</p>
            <ul>
                <li><strong>Cookies essentiels :</strong> Ces cookies sont nécessaires au fonctionnement du site et ne
                    peuvent
                    pas être désactivés. Ils permettent des fonctionnalités de base comme la navigation et l'accès aux
                    zones
                    sécurisées.</li>
                <li><strong>Cookies de performance :</strong> Ces cookies collectent des informations sur la manière
                    dont les utilisateurs interagissent avec <b>Ditotase Magschool</b>, comme les fonctionnalités les plus 
                    utilisées. Ces données nous aident à
                    améliorer le
                    site.</li>
                <li><strong>Cookies fonctionnels :</strong> Ces cookies permettent au site de se souvenir de vos choix,
                    comme
                    votre langue ou région, pour offrir une expérience personnalisée.</li>
                <li><strong>Cookies de ciblage :</strong> Ces cookies sont utilisés pour afficher des publicités
                    pertinentes
                    basées sur vos intérêts.</li>
            </ul>

            <h2>Durée de conservation des cookies</h2>
            <p>Les cookies que nous utilisons ont des durées de conservation différentes :</p>
            <ul>
                <li><strong>Cookies de session :</strong> Ces cookies sont temporaires et sont supprimés lorsque vous
                    fermez
                    votre navigateur.</li>
                <li><strong>Cookies persistants :</strong> Ces cookies restent sur votre appareil jusqu'à leur
                    expiration ou
                    jusqu'à ce que vous les supprimiez.</li>
            </ul>

            <h2>Cookies tiers</h2>
            <p>Nous pouvons également utiliser des cookies tiers, comme ceux de Google Analytics, pour analyser le
                trafic sur
                notre site. Ces tiers peuvent collecter des informations sur votre utilisation du site.</p>

            <h2>Vos choix concernant les cookies</h2>
            <p>Vous pouvez configurer votre navigateur pour accepter ou refuser les cookies. Notez que certaines
